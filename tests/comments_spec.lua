    H.save()
    H.cursor(3, "Commented")
    comments.delete()
    H.save()
    assert.equals(0, #H.comments())
    in_panel(function() comments.undo() end)
    assert.equals(1, #H.comments())
    H.reopen()
    local list = H.comments()
    assert.equals(1, #list)
    assert.same({ "A comment", { "Its reply" } }, { list[1].text, vim.tbl_map(function(r) return r.text end, list[1].replies) })
    local m = api.nvim_buf_get_extmarks(0, neo.ns.comment, 0, -1, { details = true })[1]
