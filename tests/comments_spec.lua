describe("writing a comment in a buffer", function()
  local function write_buffer(text, close)
    assert.equals("acwrite", vim.bo.buftype)
    api.nvim_buf_set_lines(0, 0, -1, false, vim.split(text, "\n"))
    vim.cmd(close and "wq" or "write")
    vim.wait(50, function() return false end)
  end

  it("adds the reply when it closes (:wq): what was written last, one reply", function()
    local path = H.copy("rich.docx")
    H.open(path)
    local doc = api.nvim_get_current_buf()
    H.cursor(3, "Commented")
    comments.reply()
    write_buffer("A reply\nin two lines")
    write_buffer("A reply, edited", true)
    assert.equals(doc, api.nvim_get_current_buf()) -- (back in the document)
    assert.same({ "A reply, edited" }, vim.tbl_map(function(r) return r.text end, H.comments()[1].replies))
    H.reopen()
    assert.same({ "A reply, edited" }, vim.tbl_map(function(r) return r.text end, H.comments()[1].replies))
  end)

  it("adds a new comment where it was asked for, also if the text moved meanwhile", function()
    H.open(H.copy("rich.docx"))
    local doc = api.nvim_get_current_buf()
    H.cursor(12, "Last")
    comments.add()
    local row = H.row(1)
    api.nvim_buf_call(doc, function() api.nvim_buf_set_lines(doc, row - 1, row - 1, false, { "A new first paragraph.", "" }) end)
    write_buffer("On the last one", true)
    H.reopen()
    local list = H.comments()
    assert.equals(2, #list)
    local mark = vim.iter(api.nvim_buf_get_extmarks(0, neo.ns.comment, 0, -1, { details = true })):find(function(m)
      return neo.docs[api.nvim_get_current_buf()].comment[m[1]].text == "On the last one"
    end)
    assert.truthy(H.lines()[mark[2] + 1]:find("^Last paragraph"), H.lines()[mark[2] + 1])
  end)

  it("saves the document with :w in the comments panel", function()
    local path = H.copy("rich.docx")
    H.open(path)
    H.cursor(3, "Commented")
    comments.reply("Saved from the panel")
    assert.is_true(vim.bo.modified)
    vim.cmd("Neoffice comments")
    vim.cmd("write")
    assert.equals("PK", H.bytes(path):sub(1, 2)) -- (a document still, written by neoffice: not the buffer's text)
    vim.cmd("Neoffice comments")
    assert.is_false(vim.bo.modified)
    H.reopen()
    assert.equals("Saved from the panel", H.comments()[1].replies[1].text)
  end)

  it("writes a reply as Word does: on the comment's text, with its reference mark", function()
    local path = H.copy("rich.docx")
    H.open(path)
    H.cursor(3, "Commented")
    comments.reply("Threaded")
    H.save()
    local doc, cmts = zip.read(path, "word/document.xml"), zip.read(path, "word/comments.xml")
    local id = cmts:match('<w:comment w:id="(%d+)"[^>]*>[^%z]-Threaded')
    assert.truthy(id, cmts)
    for _, tag in ipairs({ "commentRangeStart", "commentRangeEnd", "commentReference" }) do
      assert.truthy(doc:find("<w:" .. tag .. ' w:id="' .. id .. '"/>', 1, true), tag)
    end
    local reply = cmts:match('<w:comment w:id="' .. id .. '".-</w:comment>')
    assert.truthy(reply:find("<w:annotationRef/>", 1, true), reply)
    H.reopen()
    assert.equals(1, #H.comments()) -- (one comment, its reply in it)
    assert.equals("Threaded", H.comments()[1].replies[1].text)
  end)
end)

