describe("undo in the comments panel", function()
  local function in_panel(fn)
    vim.cmd("Neoffice comments")
    fn()
    vim.cmd("Neoffice comments")
  end

  it("undoes and redoes a reply, a resolve and an edit", function()
    H.open(H.copy("rich.docx"))
    H.cursor(3, "Commented")
    comments.reply("A reply")
    comments.resolve()
    H.cursor(3, "Commented")
    comments.edit()
    api.nvim_buf_set_lines(0, 0, 1, false, { "Edited" })
    vim.cmd("wq")
    vim.wait(50, function() return false end)
    local c = H.comments()[1]
    assert.same({ "Edited", true, 1 }, { c.text, c.resolved, #c.replies })
    in_panel(function()
      comments.undo()
      comments.undo()
    end)
    assert.same({ "A comment", false, 1 }, { c.text, c.resolved, #c.replies })
    in_panel(function()
      comments.undo()
      comments.redo()
      comments.redo()
    end)
    assert.same({ "A comment", true, 1 }, { c.text, c.resolved, #c.replies })
  end)

  it("puts a deleted comment back on its text, also after the deletion was saved", function()
    local path = H.copy("rich.docx")
    H.open(path)
