describe("undo in the comments panel, and the document's modified flag", function()
  local function undo(dir)
    vim.cmd("Neoffice comments")
    if dir == "redo" then comments.redo() else comments.undo() end
    vim.cmd("Neoffice comments")
  end

  it("is cleared when undone back to the document as saved, and only then", function()
    H.open(H.copy("rich.docx"))
    H.cursor(3, "Commented")
    comments.resolve()
    assert.is_true(vim.bo.modified)
    undo()
    assert.is_false(vim.bo.modified) -- (as opened)
    comments.reply("Kept")
    H.save()
    undo()
    assert.is_true(vim.bo.modified) -- (the saved document has the reply)
    undo("redo")
    assert.is_false(vim.bo.modified) -- (as saved again)
  end)

  it("stays set when the text, or something else, changed meanwhile", function()
    H.open(H.copy("rich.docx"))
    H.replace(1, "Introduction", "Intro")
    H.cursor(3, "Commented")
    comments.resolve()
    undo()
    assert.is_true(vim.bo.modified) -- (its text changed)
    H.open(H.copy("rich.docx"))
    vim.cmd("Neoffice numbers")
    H.cursor(3, "Commented")
    comments.resolve()
    undo()
    assert.is_true(vim.bo.modified) -- (its heading numbers changed)
  end)
end)

