-- neoffice.read: documents for other plugins (each paragraph as sent and as revised, its comments).
local H = dofile("tests/helpers.lua")
local read = require("neoffice.read")
local api = vim.api

local function text(chars)
  return table.concat(vim.tbl_map(function(c) return c.ch end, chars))
end

describe("neoffice.read", function()
  it("tells documents, their file and whether they have tracked changes", function()
    local path = H.copy("rich.docx")
    local buf = H.open(path)
    assert.is_true(read.is_document(buf))
    assert.equals(path, read.path(buf))
    assert.is_true(read.has_changes(buf))
    vim.cmd("enew")
    assert.is_false(read.is_document(api.nvim_get_current_buf()))
    assert.is_nil(read.paragraphs(api.nvim_get_current_buf()))
  end)

  it("gives each paragraph as sent and as revised, with its formatting and comments", function()
    local buf = H.open(H.copy("rich.docx"))
    H.set(12, "Last paragraph.")
    H.save()
    vim.cmd("Neoffice track on")
    H.replace(12, "Last", "*Final*")
    local p = read.paragraphs(buf)
    assert.equals("Last paragraph.", text(p[12].sent))
    assert.equals("Final paragraph.", text(p[12].revised))
    assert.is_true(p[12].revised[1].i)
    local commented = vim.iter(p):find(function(x) return #x.comments > 0 end)
    assert.equals("Alice", commented.comments[1].author)
    assert.is_false(commented.comments[1].resolved)
  end)

  it("reads a document file, and says why it can't", function()
    local paragraphs = read.file(H.copy("rich.odt"))
    assert.truthy(#paragraphs > 5)
    local none, err = read.file(vim.fn.tempname() .. "/missing.docx")
    assert.is_nil(none)
    assert.truthy(err)
  end)
end)
